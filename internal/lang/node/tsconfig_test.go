// A tsconfig is JSON with comments and trailing commas, which the standard
// decoder rejects. Every project generated by `tsc --init` has both.
func TestATsconfigMayHaveCommentsAndTrailingCommas(t *testing.T) {
	files := program(t, map[string]string{
		"tsconfig.json": `{
  // The project's own code is reached through "@/".
  "compilerOptions": {
    /* block comments too */
    "baseUrl": ".",
    "paths": {
      "@/*": ["src/*"], // a trailing comment
    },
  },
}`,
		"src/server.ts": `import { pets } from "@/store";`,
		"src/store.ts":  `export const pets = 1;`,
	})

	got, unresolved := closure(files, "src/server.ts", nil)
	if len(unresolved) != 0 {
		t.Fatalf("unresolved = %+v", unresolved)
	}
	if !contains(got, "src/store.ts") {
		t.Errorf("closure = %v", got)
	}
}

// A `//` inside a string is not a comment. A URL in a paths entry is exactly
// where one shows up, and a regex-based stripper eats the rest of the line.
func TestStrippingCommentsLeavesStringsAlone(t *testing.T) {
	got := string(stripJSONC([]byte(`{"a": "https://example.com/x", "b": 1}`)))
	if want := `{"a": "https://example.com/x", "b": 1}`; got != want {
		t.Errorf("stripJSONC = %q, want %q", got, want)
	}
}

// One level of `extends` is read. Deeper than that is *said*, because a
// configuration read halfway resolves some aliases and not others, which is
// the one outcome worse than reading none.
func TestExtendsIsReadOnceAndDepthIsReported(t *testing.T) {
	files := program(t, map[string]string{
		"tsconfig.base.json": `{ "compilerOptions": { "baseUrl": ".", "paths": { "@/*": ["src/*"] } } }`,
		"tsconfig.json":      `{ "extends": "./tsconfig.base.json" }`,
		"src/server.ts":      `import { pets } from "@/store";`,
		"src/store.ts":       `export const pets = 1;`,
	})
	// `extends` names a file, not a directory: the base is read from the
	// directory it sits in.
	_, unresolved := closure(files, "src/server.ts", nil)
	for _, u := range unresolved {
		if strings.Contains(u.Why, "level deep") {
			t.Fatalf("one level should be read, not reported: %+v", u)
		}
	}
}

// A tsconfig this compiler cannot parse is reported once, not once per import.
func TestAnUnreadableTsconfigIsReportedOnce(t *testing.T) {
	files := program(t, map[string]string{
		"tsconfig.json": `{ this is not json`,
		"server.ts":     "import a from \"./a.js\";\nimport b from \"./b.js\";\n",
	})

	_, unresolved := closure(files, "server.ts", nil)
	config := 0
	for _, u := range unresolved {
		if strings.Contains(u.Why, "could not be read") {
			config++
		}
	}
	if config != 1 {
		t.Errorf("the unreadable tsconfig was reported %d times, want once: %+v", config, unresolved)
	}
}

// A type-only import reaches nothing at runtime: every TypeScript build erases
// the statement, and esbuild leaves the module out of the bundle. Following it
// into the closure puts that module in the unit anyway -- and when it declares
// a store, the unit is wired to one it never touches and granted IAM for it.
func TestATypeOnlyImportIsNotFollowed(t *testing.T) {
	files := program(t, map[string]string{
		"summary.ts": `import type { Pet } from "./store.js";
export async function describe(p: Pet): Promise<string> { return p.name; }`,
		"store.ts": `export interface Pet { name: string }
export const pets = 1;`,
	})

	got, _ := closure(files, "summary.ts", nil)
	if contains(got, "store.ts") {
		t.Errorf("closure = %v; a type-only import must not pull the module in", got)
	}
}

// The inline form is a different statement: the module is genuinely imported,
// and dropping it would leave a bundle missing a file the program calls into.
func TestAnInlineTypeImportIsStillAnImport(t *testing.T) {
	files := program(t, map[string]string{
		"server.ts": `import { type Pet, readPet } from "./store.js";
export const x = readPet;`,
		"store.ts": `export interface Pet { name: string }
export function readPet(): Pet { return { name: "x" }; }`,
	})

	got, _ := closure(files, "server.ts", nil)
	if !contains(got, "store.ts") {
		t.Errorf("closure = %v, want store.ts", got)
	}
}

// A tsconfig is user input, and a pattern whose prefix and suffix overlap the
// specifier crashed the resolver: "@a/b" starts with "@a/" and ends with "/b"
// while being shorter than both together, and the slice between them ran
// backwards.
func TestAnOverlappingAliasPatternDoesNotPanic(t *testing.T) {
	files := program(t, map[string]string{
		"tsconfig.json": `{ "compilerOptions": { "paths": { "@a/*/b": ["src/*"] } } }`,
		"server.ts":     `import x from "@a/b";`,
	})

	// The assertion is that this returns at all.
	if _, unresolved := closure(files, "server.ts", nil); len(unresolved) != 0 {
		t.Errorf("the specifier matches no pattern, so it is a package: %+v", unresolved)
	}
}
