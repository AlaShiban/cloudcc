// program builds a source set from a map of path to content, parsing whatever
// the Node frontend claims and leaving the rest -- a tsconfig.json is not
// source, and is read as data.
func program(t *testing.T, files map[string]string) *source.Set {
	t.Helper()
	set := source.NewSet("/tmp")
	t.Cleanup(set.Close)
	for p, content := range files {
		f := &source.File{Path: p, Content: []byte(content)}
		if (Frontend{}).Owns(p) {
			if err := (Frontend{}).Parse(f); err != nil {
				t.Fatalf("parsing %s: %v", p, err)
			}
		}
		set.Add(f)
	}
	return set
}

// A path alias is how most TypeScript projects of any size import their own
// code. Before this, the specifier was not relative, so it was taken for an npm
// package: the module never entered the closure, never reached the bundle, and
// the first sign was esbuild failing to resolve it -- minutes later, from a
// different tool, naming the specifier but not the reason.
func TestPathAliasesResolveToLocalFiles(t *testing.T) {
	files := program(t, map[string]string{
		"tsconfig.json": `{
  "compilerOptions": {
    "baseUrl": ".",
    "paths": { "@/*": ["src/*"] }
  }
}`,
		"src/server.ts": `import { pets } from "@/store";`,
		"src/store.ts":  `export const pets = 1;`,
	})

	got, unresolved := closure(files, "src/server.ts", nil)
	if len(unresolved) != 0 {
		t.Fatalf("unresolved = %+v", unresolved)
	}
	if want := []string{"src/server.ts", "src/store.ts"}; !reflect.DeepEqual(got, want) {
		t.Errorf("closure = %v, want %v", got, want)
	}
}

// The most specific pattern wins, which is what TypeScript does and what a
// project with both a general and a narrow alias relies on.
func TestTheMostSpecificAliasWins(t *testing.T) {
	files := program(t, map[string]string{
		"tsconfig.json": `{
  "compilerOptions": {
    "paths": {
      "@app/*": ["wrong/*"],
      "@app/models/*": ["right/*"]
    }
  }
}`,
		"server.ts":           `import { Pet } from "@app/models/pet";`,
		"right/pet.ts":        `export const Pet = 1;`,
		"wrong/models/pet.ts": `export const Pet = 2;`,
	})

	got, _ := closure(files, "server.ts", nil)
	if !contains(got, "right/pet.ts") || contains(got, "wrong/models/pet.ts") {
		t.Errorf("closure = %v, want the more specific pattern to win", got)
	}
}

// baseUrl alone, with no paths at all, is the other common shape.
func TestBaseURLResolvesBareSpecifiers(t *testing.T) {
	files := program(t, map[string]string{
		"tsconfig.json": `{ "compilerOptions": { "baseUrl": "src" } }`,
		"src/server.ts": `import { pets } from "store";`,
		"src/store.ts":  `export const pets = 1;`,
	})

	got, unresolved := closure(files, "src/server.ts", nil)
	if len(unresolved) != 0 {
		t.Fatalf("unresolved = %+v", unresolved)
	}
	if !contains(got, "src/store.ts") {
		t.Errorf("closure = %v, want src/store.ts", got)
	}
}

// The point of the whole exercise: an alias that maps to nothing is *reported*.
// Silence here is what the old behaviour did, and it is worse than the error,
// because the program looks compiled right up until the bundler runs.
func TestAnAliasThatMapsToNothingIsReported(t *testing.T) {
	files := program(t, map[string]string{
		"tsconfig.json": `{ "compilerOptions": { "paths": { "@/*": ["src/*"] } } }`,
		"server.ts":     `import { pets } from "@/store";`,
	})

	_, unresolved := closure(files, "server.ts", nil)
	if len(unresolved) != 1 {
		t.Fatalf("unresolved = %+v, want the alias reported", unresolved)
	}
	if unresolved[0].Rendered != "@/store" {
		t.Errorf("rendered = %q", unresolved[0].Rendered)
	}
	if !strings.Contains(unresolved[0].Why, "tsconfig") {
		t.Errorf("the reason should name where the mapping came from: %q", unresolved[0].Why)
	}
}

